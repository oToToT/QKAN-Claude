"""Families of dynamical systems for in-context forecasting.

The six one-step benchmarks of the paper are single trajectories: train and
test windows come from the same system, so one fixed predictor is enough and a
closed-form linear AR(8) beats every model (REPORT.md, Sec. 5.6).  Fast-weight
memory can only matter when the window carries information that the slow
weights cannot hold.  Here every sequence is generated by the *same kind* of
system with *different physical parameters*, and the train / validation / test
splits contain different sequences.  A model has to identify the system from
the window it is given.

Families (all scalar series, generated in float64):

``shm``    damped oscillation  A exp(-gamma t) cos(omega t + phi), random
           (omega, gamma, A, phi) - the paper's "damped SHM" with unknown
           frequency and damping.  Obeys an exact AR(2) recurrence whose two
           coefficients depend on the sequence.
``tones``  sum of two such damped oscillations (exact AR(4) per sequence).
``jc``     open Jaynes-Cummings qubit excitation <sigma+ sigma-> with random
           coupling g, detuning, cavity loss and initial photon amplitudes -
           the paper's JC benchmark with unknown Hamiltonian parameters.
``henon``  Henon map x' = 1 - a x^2 + b x_prev with random (a, b): chaotic and
           nonlinear; linear in its parameters only in the features (x^2, x_prev).
``duffing`` unforced Duffing oscillator x'' + d x' + a x + b x^3 = 0 with
           random (d, a, b): nonlinear, amplitude-dependent frequency.

``noise`` adds white observation noise (in units of the normalised series).
"""

from __future__ import annotations

import numpy as np
from scipy.integrate import solve_ivp
from scipy.linalg import expm


def _shm(rng, n_seq, length):
    t = np.arange(length)[None, :]
    om = rng.uniform(0.25, 1.4, (n_seq, 1))  # rad / step: 4.5 .. 25 samples per period
    ga = rng.uniform(0.0, 0.03, (n_seq, 1))
    amp = rng.uniform(0.5, 1.0, (n_seq, 1))
    ph = rng.uniform(0.0, 2 * np.pi, (n_seq, 1))
    return amp * np.exp(-ga * t) * np.cos(om * t + ph)


def _tones(rng, n_seq, length):
    return 0.6 * (_shm(rng, n_seq, length) + _shm(rng, n_seq, length))


def _jc(rng, n_seq, length, dt=0.08, n_fock=6):
    a = np.diag(np.sqrt(np.arange(1, n_fock)), 1)
    sm = np.array([[0.0, 1.0], [0.0, 0.0]])  # |g><e|, basis (g, e)
    a_full = np.kron(np.eye(2), a)
    sm_full = np.kron(sm, np.eye(n_fock))
    dim = 2 * n_fock
    eye = np.eye(dim)
    num_a = a_full.T @ a_full
    num_q = sm_full.T @ sm_full
    inter = sm_full @ a_full.T + sm_full.T @ a_full
    proj = num_q.reshape(-1, order="F")
    out = np.empty((n_seq, length))
    for i in range(n_seq):
        g = rng.uniform(0.5 * np.pi, 1.5 * np.pi)
        delta = rng.uniform(-np.pi, np.pi)  # qubit - cavity detuning (rotating frame)
        kappa = rng.uniform(0.02, 0.3)
        ham = delta * num_q + g * inter
        c = np.sqrt(kappa) * a_full
        cdc = c.T @ c
        liouv = (
            -1j * (np.kron(eye, ham) - np.kron(ham.T, eye))
            + np.kron(c.conj(), c)
            - 0.5 * np.kron(eye, cdc)
            - 0.5 * np.kron(cdc.T, eye)
        )
        # qubit excited, field in a random superposition of 0, 1, 2 photons
        field = np.zeros(n_fock, dtype=complex)
        field[:3] = rng.normal(size=3) + 1j * rng.normal(size=3)
        field /= np.linalg.norm(field)
        psi = np.kron(np.array([0.0, 1.0]), field)
        rho = np.outer(psi, psi.conj()).reshape(-1, order="F")
        step = expm(liouv * dt)
        for k in range(length):
            out[i, k] = np.real(proj.conj() @ rho)
            rho = step @ rho
    return 2.0 * out - 1.0


def _henon(rng, n_seq, length):
    out = np.empty((n_seq, length))
    i = 0
    while i < n_seq:
        a, b = rng.uniform(1.0, 1.4), rng.uniform(0.1, 0.3)
        x = np.empty(length + 100)
        x[0], x[1] = rng.uniform(-0.3, 0.3, 2)
        ok = True
        for k in range(1, length + 99):
            x[k + 1] = 1.0 - a * x[k] ** 2 + b * x[k - 1]
            if abs(x[k + 1]) > 3.0:
                ok = False
                break
        if ok:
            out[i] = x[100:] / 1.5
            i += 1
    return out


def _duffing(rng, n_seq, length, dt=0.25):
    out = np.empty((n_seq, length))
    t = np.arange(length) * dt
    for i in range(n_seq):
        d, a, b = rng.uniform(0.02, 0.2), rng.uniform(0.5, 2.0), rng.uniform(0.5, 4.0)
        x0, v0 = rng.uniform(-1.0, 1.0), rng.uniform(-1.0, 1.0)
        sol = solve_ivp(lambda _, s: [s[1], -d * s[1] - a * s[0] - b * s[0] ** 3], (0.0, t[-1]), [x0, v0],
                        t_eval=t, rtol=1e-9, atol=1e-11)
        out[i] = sol.y[0]
    return out


FAMILIES = {"shm": _shm, "tones": _tones, "jc": _jc, "henon": _henon, "duffing": _duffing}

FAMILY_INFO = {
    "shm": "damped oscillation, random frequency / damping / amplitude / phase (exact AR(2) per sequence)",
    "tones": "two damped oscillations (exact AR(4) per sequence)",
    "jc": "open Jaynes-Cummings <s+ s->, random g, detuning, kappa and initial field",
    "henon": "Henon map with random (a, b)",
    "duffing": "unforced Duffing oscillator with random damping and stiffness",
}


def make_family(name: str, n_seq: int, length: int, seed: int, noise: float = 0.0) -> np.ndarray:
    """``(n_seq, length)`` float64 sequences; ``seed`` fixes parameters and noise."""
    rng = np.random.default_rng(seed)
    s = FAMILIES[name](rng, n_seq, length)
    if noise > 0:
        s = s + noise * rng.normal(size=s.shape)
    return s


def family_windows(seqs: np.ndarray, window: int, per_seq: int, seed: int):
    """Random windows: ``x`` (n, window, 1) and one-step targets ``y`` (n, 1)."""
    rng = np.random.default_rng(seed)
    n_seq, length = seqs.shape
    starts = rng.integers(0, length - window, (n_seq, per_seq))
    rows = np.repeat(np.arange(n_seq), per_seq)
    idx = starts.reshape(-1, 1) + np.arange(window + 1)[None, :]
    w = seqs[rows[:, None], idx]
    return w[:, :window, None], w[:, window:]


def family_splits(name: str, window: int, noise: float = 0.0, length: int = 96,
                  n_train: int = 400, n_val: int = 100, n_test: int = 300, per_seq: int = 8,
                  data_seed: int = 1234):
    """Train / validation / test windows from *disjoint sets of sequences*."""
    out = {}
    for i, (split, n) in enumerate([("train", n_train), ("val", n_val), ("test", n_test)]):
        seqs = make_family(name, n, max(length, window + 2), data_seed + i, noise)
        out[split] = family_windows(seqs, window, per_seq, data_seed + 10 + i)
    return out
